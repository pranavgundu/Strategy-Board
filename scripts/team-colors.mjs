// regenerates src/lib/domain/team-color-table.ts from the scouting app's team color source
// usage: node scripts/team-colors.mjs [path/to/team_to_color.dart]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = process.argv[2] ?? fileURLToPath(new URL("../../Scouting-2026/lib/models/team_to_color.dart", import.meta.url));
const target = fileURLToPath(new URL("../src/lib/domain/team-color-table.ts", import.meta.url));
const dart = readFileSync(source, "utf8");

const hex = (...channels) => `#${channels.map((value) => Number(value).toString(16).padStart(2, "0")).join("")}`;
const table = [...dart.matchAll(/^\s*(\d+):\s*Color\(0x[0-9a-fA-F]{2}([0-9a-fA-F]{6})\),/gm)]
  .map(([, team, rgb]) => [Number(team), `#${rgb.toLowerCase()}`]);
const palette = dart.slice(dart.indexOf("const List<Color> colors"));
const fallback = [...palette.matchAll(/Color\.fromARGB\(\s*\d+\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)/g)]
  .map(([, red, green, blue]) => hex(red, green, blue));
if (!table.length || !fallback.length) throw new Error(`No team colors found in ${source}`);

writeFileSync(target, [
  "// generated by scripts/team-colors.mjs from the scouting app's lib/models/team_to_color.dart - do not edit by hand",
  "export const TEAM_COLOR_TABLE: Readonly<Record<number, string>> = {",
  ...table.map(([team, color]) => `  ${team}: "${color}",`),
  "};",
  "",
  "export const FALLBACK_TEAM_COLORS: readonly string[] = [",
  ...fallback.map((color) => `  "${color}",`),
  "];",
  "",
].join("\n"));
console.log(`Wrote ${table.length} team colors and ${fallback.length} fallback colors to ${target}`);
